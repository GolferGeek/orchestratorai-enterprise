BEGIN
  IF to_regclass('ambient.a2a_inbound_nonces_expires_at_idx') IS NULL
     AND to_regclass('ambient.ambient_a2a_inbound_nonces_expires_at_idx') IS NOT NULL THEN
    ALTER INDEX ambient.ambient_a2a_inbound_nonces_expires_at_idx RENAME TO a2a_inbound_nonces_expires_at_idx;
  END IF;
